test("modeled approval excludes reconciliation code and remains exactly once", () => {
  const request = { baseAmount: 100000, uniqueCode: 237, tokens: 100, status: "submitted" };
  let balanceTokens = 0;
  const ledger = new Set();
  const approve = () => {
    if (request.status === "approved") return;
    if (!ledger.has("request-1")) {
      balanceTokens += request.tokens;
      ledger.add("request-1");
    }
    request.status = "approved";
  };
  assert.equal(request.baseAmount + request.uniqueCode, 100237);
  approve();
  approve();
  assert.equal(balanceTokens, 100);
  assert.equal(ledger.size, 1);
});

