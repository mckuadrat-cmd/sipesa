test("modeled DTO amount aliases and historical fallback stay equivalent", () => {
  const mapDto = (amountRequested, uniqueCode) => ({
    amount_idr: amountRequested,
    base_amount: amountRequested,
    amount_requested: amountRequested,
    unique_code: uniqueCode,
    transfer_amount: amountRequested + (uniqueCode ?? 0),
  });
  const current = mapDto(100000, 237);
  assert.equal(current.amount_requested, current.base_amount);
  assert.equal(current.amount_requested, current.amount_idr);
  assert.equal(current.transfer_amount, current.amount_requested + current.unique_code);
  const historical = mapDto(100000, null);
  assert.equal(historical.transfer_amount, historical.amount_requested);
  assert.equal(historical.transfer_amount, historical.base_amount);
});

